"use strict";
const assert = require("node:assert/strict");
const { isLegacyCustomerCandidate: customer, isSellerStatusCandidate: seller } = require("./identity-recovery-policy-v54.cjs");
const legacy = { role: "seller", isActive: true };
const ctx = { sellerId: "", sellerExists: false, selfSellerExists: false, ownedSellerCount: 0, authDisabled: false };
assert.equal(customer(legacy, ctx), true);
assert.equal(customer({ ...legacy, accountStatus: "disabled" }, ctx), false);
assert.equal(customer({ ...legacy, schemaVersion: 2 }, ctx), false);
assert.equal(customer({ ...legacy, sellerId: "abc" }, { ...ctx, sellerId: "abc" }), false);
assert.equal(customer(legacy, { ...ctx, sellerExists: true }), false);
assert.equal(customer(legacy, { ...ctx, ownedSellerCount: 1 }), false);
assert.equal(customer(legacy, { ...ctx, authDisabled: true }), false);
assert.equal(customer({ role: "admin", isActive: true }, ctx), false);
const sctx = { uid: "abc", seller: { ownerUid: "abc", accountStatus: "active" }, sellerExists: true, authDisabled: false };
assert.equal(seller(legacy, sctx), true);
assert.equal(seller(legacy, { ...sctx, seller: { ownerUid: "other", accountStatus: "active" } }), false);
assert.equal(seller(legacy, { ...sctx, seller: { ownerUid: "abc", accountStatus: "disabled" } }), false);
assert.equal(seller({ ...legacy, suspended: true }, sctx), false);
assert.equal(seller({ ...legacy, accountStatus: "suspended" }, sctx), false);
assert.equal(seller(legacy, { ...sctx, authDisabled: true }), false);
